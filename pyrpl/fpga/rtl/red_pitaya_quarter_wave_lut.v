module red_pitaya_quarter_wave_lut #(
    parameter     LUTSZ     = 11,  
    parameter     LUTBITS   = 14,  
    parameter     PHASEBITS = 32 
)
(
    input clk_i,
    input rstn_i,

    input  [PHASEBITS-1:0] phase_a_in   ,
    input  [PHASEBITS-1:0] phase_b_in   ,

    output [LUTBITS-1:0] sin_a_o        ,
    output [LUTBITS-1:0] sin_b_o        
);

reg [LUTBITS-1:0] sin_a;
reg [LUTBITS-1:0] sin_b;

assign sin_a_o = sin_a;
assign sin_b_o = sin_b;

//lut data block
reg [LUTBITS-1-1:0] lut_quarter_sine [0:(1<<LUTSZ)-1];

wire [PHASEBITS-1:0] wwphase_a;
wire [PHASEBITS-1:0] wwphase_b;
wire [LUTBITS-1:0] wphase_a; // FIXME: Ich glaube, wphase sollte nicht LUTBITS wide sein oder? LUTSZ eher.
wire [LUTBITS-1:0] wphase_b; // FIXME: Ich glaube, wphase sollte nicht LUTBITS wide sein oder? LUTSZ eher.
wire invertphase_a;
wire invertphase_b;
wire invertsignal_a;
wire invertsignal_b;
reg invertsignal_a_reg;
reg invertsignal_b_reg;
reg invertsignal_a_reg_reg;
reg invertsignal_b_reg_reg;
reg [LUTBITS-1:0] sin_a_reg;
reg [LUTBITS-1:0] sin_b_reg;

reg [LUTBITS-1:0] phase_a;
reg [LUTBITS-1:0] phase_b;

assign wwphase_a = phase_a_in;
assign wwphase_b = phase_b_in;
assign wphase_a = wwphase_a[PHASEBITS-2-1:PHASEBITS-2-LUTSZ];
assign wphase_b = wwphase_b[PHASEBITS-2-1:PHASEBITS-2-LUTSZ];
assign invertphase_a  = wwphase_a[PHASEBITS-1-1]; 
assign invertphase_b  = wwphase_b[PHASEBITS-1-1]; 
assign invertsignal_a = wwphase_a[PHASEBITS-1];
assign invertsignal_b = wwphase_b[PHASEBITS-1];


//main loop
always @(posedge clk_i) begin
    // 1) Next-phase computations:
    phase_a <= invertphase_a ? (~wphase_a) : wphase_a;
    phase_b <= invertphase_b ? (~wphase_b) : wphase_b;

    // 2) Register the sign bits twice, such that they are ready in the same cycle as the sine registers.
    invertsignal_a_reg <= invertsignal_a;
    invertsignal_b_reg <= invertsignal_b;
    invertsignal_a_reg_reg <= invertsignal_a_reg;
    invertsignal_b_reg_reg <= invertsignal_b_reg;

    // 3) Read LUT outputs for the next cycle
    sin_a_reg <= lut_quarter_sine[phase_a];
    sin_b_reg <= lut_quarter_sine[phase_b];

    // 4) Invert sign if needed
    sin_a <= invertsignal_a_reg_reg ? ((~sin_a_reg)+'b1) : sin_a_reg; 
    sin_b <= invertsignal_b_reg_reg ? ((~sin_b_reg)+'b1) : sin_b_reg;  
end


