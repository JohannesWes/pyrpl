// Description: 
//  
// This module implements a pipelined sine wave generator using a quarter-wave
// Look-Up Table (LUT). It takes two phase values phase_a_in and phase_b_in.
// It outputs two sine waves: sin(phase_a_in) and sin(phase_b_in). 
//
// Functionality:
// - Input phase is FULL_PHASE_WIDTH bits, representing 0 to 2*pi.
// - The top two bits of the full phase determine the quadrant and necessary
//   transformations (address inversion for LUT, output sign inversion).
// - A quarter-wave LUT (first quadrant, 0 to pi/2) stores sine magnitudes.
//   The LUT is addressed by LUTSZ bits extracted from the input phase.
// - Output sine values are LUTBITS bits in two's complement format.
// - Maximum positive output:  (2**(LUTBITS-1)) - 1
// - Maximum negative output: -((2**(LUTBITS-1)) - 1)
//
// Pipelining:
// The module has a 3-cycle latency from phase input to sine output:
// - Cycle 0 (Input): Phase inputs are received. Combinatorial logic calculates
//                    LUT address components and control signals.
// - Cycle 1 (Reg Stage 1): Mapped LUT address and first stage of sign control
//                          bit are registered.
// - Cycle 2 (Reg Stage 2): LUT is read using registered address. Second stage of
//                          sign control bit is registered.
// - Cycle 3 (Reg Stage 3): Sign inversion is applied to the LUT output.
//                          Final sine value is registered and available at output.
//
// 
